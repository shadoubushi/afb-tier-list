/* =====================================================
   DISPLAY HEROES
   ===================================================== */


   


function displayHeroes(heroList) {


    /* -------------------------
       CLEAR CURRENT HEROES
       ------------------------- */

    strGrid.innerHTML = "";

    agiGrid.innerHTML = "";

    intGrid.innerHTML = "";


    /* -------------------------
       CREATE HERO CARDS
       ------------------------- */

    for (const name in heroList) {


        const hero =
            heroList[name];


        const card =
            document.createElement("div");


        card.className =
            "hero-card";


        card.innerHTML = `

            <img
                src="${hero.image}"
                alt="${name}"
            >

            <p>
                ${name}
            </p>

        `;


        /* -------------------------
           OPEN POPUP
           ------------------------- */

        card.onclick = function() {

            openHero(name);

        };


        /* -------------------------
           PLACE HERO BY ATTRIBUTE
           ------------------------- */

        if (
            hero.attribute === "STR"
        ) {

            strGrid.appendChild(card);

        }

        else if (
            hero.attribute === "AGI"
        ) {

            agiGrid.appendChild(card);

        }

        else if (
            hero.attribute === "INT"
        ) {

            intGrid.appendChild(card);

        }

    }

}




/* =====================================================
   FILTER + SEARCH + SORT
   ===================================================== */


function updateHeroDisplay() {


    /* -------------------------
       GET SEARCH TEXT
       ------------------------- */

    const searchText =
        searchBar.value.toLowerCase().trim();


    /* -------------------------
       START WITH ALL HEROES
       ------------------------- */

    let filteredHeroes =Object.entries(heroes);


    /* =================================================
       SEARCH
       ================================================= */

       if (searchText !== "") {

        filteredHeroes = filteredHeroes.filter(([name, hero]) => {
    
            const nameMatch =
                name.toLowerCase().includes(searchText);
    
            const keywordMatch =
                hero.keywords &&
                hero.keywords.some(keyword =>
                    keyword.toLowerCase().includes(searchText)
                );
    
            return nameMatch || keywordMatch;
    
        });
    
    }


    /* =================================================
       FREE / PAID FILTER
       ================================================= */

    if (
        availabilityFilter.value !== "all"
    ) {

        filteredHeroes =
            filteredHeroes.filter(
                ([name, hero]) =>

                    hero.availability ===
                    availabilityFilter.value

            );

    }


    /* =================================================
       PRICE SORT
       ================================================= */

    if (
        priceSort.value === "high-low"
    ) {

        filteredHeroes.sort(

            ([nameA, heroA], [nameB, heroB]) =>

                heroB.price -
                heroA.price

        );

    }


    else if (
        priceSort.value === "low-high"
    ) {

        filteredHeroes.sort(

            ([nameA, heroA], [nameB, heroB]) =>

                heroA.price -
                heroB.price

        );

    }


    /* =================================================
       CONVERT ARRAY BACK TO OBJECT
       ================================================= */

    const heroObject =
        Object.fromEntries(
            filteredHeroes
        );


    /* =================================================
       DISPLAY
       ================================================= */

    displayHeroes(
        heroObject
    );

}




/* =====================================================
   SEARCH EVENT
   ================================================= */


searchBar.addEventListener(
    "input",
    updateHeroDisplay
);




/* =====================================================
   AVAILABILITY FILTER EVENT
   ================================================= */


availabilityFilter.addEventListener(
    "change",
    updateHeroDisplay
);




/* =====================================================
   PRICE SORT EVENT
   ================================================= */


priceSort.addEventListener(
    "change",
    updateHeroDisplay
);




/* =====================================================
   OPEN HERO POPUP
   ===================================================== */


function openHero(name) {


    const hero =
        heroes[name];


    /* -------------------------
       HERO NAME
       ------------------------- */

    document.getElementById(
        "heroName"
    ).innerText = name;


    /* -------------------------
       HERO IMAGE
       ------------------------- */

    document.getElementById(
        "heroImage"
    ).src = hero.image;


    /* -------------------------
       MAIN ATTRIBUTE
       ------------------------- */

    document.getElementById(
        "heroAttribute"
    ).innerText =
        hero.attribute;


    /* -------------------------
       PRICE
       ------------------------- */

    if (
        hero.availability === "free"
    ) {

        document.getElementById(
            "heroPrice"
        ).innerText = "Free";

    }

    else {

        document.getElementById(
            "heroPrice"
        ).innerText =
            `RMB ${hero.price}`;

    }


    /* =================================================
       PATCH HISTORY
       ================================================= */

    let patchHTML = "";


    hero.patches.forEach(
        patch => {


            patchHTML += `

                <div class="patch">

                    <h4>
                        Patch ${patch.version}
                    </h4>

                    <p>
                        ${patch.details}
                    </p>

                </div>

            `;

        }
    );


    document.getElementById(
        "patchInfo"
    ).innerHTML =
        patchHTML;


    /* =================================================
       SHOW POPUP
       ================================================= */

    document.getElementById(
        "heroModal"
    ).style.display =
        "block";

}




/* =====================================================
   CLOSE HERO POPUP
   ===================================================== */


function closeHero() {

    document.getElementById(
        "heroModal"
    ).style.display =
        "none";

}




/* =====================================================
   CLICK OUTSIDE POPUP TO CLOSE
   ===================================================== */


window.onclick =
    function(event) {


        const modal =
            document.getElementById(
                "heroModal"
            );


        if (
            event.target === modal
        ) {

            closeHero();

        }

    };




